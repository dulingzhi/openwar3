// Generate the DzAPI declaration table from dz_w3_plugin/src/plugin.
//
//   node tools/dzapi-gen.cjs <path-to-src-plugin> [--out file]
//
// Reads the `FUNC_ITEM(func, sig)` and `JASS_REGISTER_EX(func, name, sig)` rows of every
// `war3japi_*.cpp` file and emits ONE TypeScript table, deduplicated by name (first module
// wins), with the source module kept for grouping.
//
// This is the P0 declaration step of docs/dzapi-port.md: registering these names with their
// signatures means `jass.common`, `_G` and `jass.japi` can all reach them even before a pack
// implements the body — an unimplemented one answers its typed default and logs once, which is
// the difference between "map keeps running" and "attempt to call a nil value".

const { readFileSync, writeFileSync, readdirSync, existsSync } = require('node:fs');
const { join, resolve } = require('node:path');

const args = process.argv.slice(2);
const outAt = args.indexOf('--out');
const outFile = outAt >= 0 ? args[outAt + 1] : join(__dirname, '..', 'src', 'compat', 'lua', 'japi', 'dzapi-decl.ts');
const root = resolve(args.find((a, i) => !a.startsWith('--') && !(outAt >= 0 && i === outAt + 1)) ?? '.');
if (!existsSync(root)) {
  console.error(`not found: ${root}`);
  process.exit(2);
}

const files = readdirSync(root).filter((f) => /^war3japi.*\.cpp$/.test(f)).sort();
if (!files.length) {
  console.error(`no war3japi*.cpp under ${root}`);
  process.exit(2);
}

/** `war3japi_gui.cpp` → `gui`; `war3japi.cpp` → `platform`. */
const moduleOf = (file) => {
  const m = /^war3japi(?:_(\w+))?\.cpp$/.exec(file);
  return m ? m[1] ?? 'platform' : file;
};

const seen = new Map();
const duplicates = [];
for (const file of files) {
  const src = readFileSync(join(root, file), 'utf8');
  const add = (name, param) => {
    if (seen.has(name)) {
      duplicates.push(`${name} (${file}; first ${seen.get(name).module})`);
      return;
    }
    seen.set(name, { name, param, module: moduleOf(file) });
  };
  for (const m of src.matchAll(/FUNC_ITEM\s*\(\s*([A-Za-z0-9_]+)\s*,\s*"([^"]*)"\s*\)/g)) add(m[1], m[2]);
  for (const m of src.matchAll(/JASS_REGISTER_EX\s*\(\s*[A-Za-z0-9_]+\s*,\s*"([^"]+)"\s*,\s*"([^"]*)"\s*\)/g)) add(m[1], m[2]);
}

const rows = [...seen.values()];
const byModule = new Map();
for (const r of rows) {
  if (!byModule.has(r.module)) byModule.set(r.module, []);
  byModule.get(r.module).push(r);
}

const q = (s) => JSON.stringify(s);
let out = '';
out += '// GENERATED by tools/dzapi-gen.cjs from dz_w3_plugin/src/plugin — do not edit.\n';
out += `// ${rows.length} registrations; parse with src/compat/lua/japi/signature.ts.\n`;
out += '//\n';
out += '// These are NATIVES in the original (`RegisterNativeFunction`), not `japi_add` names. We\n';
out += '// register each as a JAPI alias so jass.japi, jass.common and _G all reach it with one\n';
out += '// signature; a pack then replaces the typed default with a real implementation.\n\n';
out += 'export interface DzapiDecl {\n  name: string;\n  param: string;\n  /** The source module (`gui`, `plus`, `extend`, `hardware`, `packet`, `db`, `platform`). */\n  module: string;\n}\n\n';
out += 'export const DZAPI: readonly DzapiDecl[] = [\n';
for (const [mod, list] of [...byModule.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  out += `  // --- ${mod} (${list.length}) ---\n`;
  for (const r of list.sort((a, b) => a.name.localeCompare(b.name))) {
    out += `  { name: ${q(r.name)}, param: ${q(r.param)}, module: ${q(r.module)} },\n`;
  }
}
out += '];\n';

writeFileSync(outFile, out);
console.log(`wrote ${outFile}: ${rows.length} declarations across ${byModule.size} modules`);
for (const [mod, list] of [...byModule.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  console.log(`  ${mod.padEnd(10)} ${list.length}`);
}
if (duplicates.length) {
  console.log(`\n${duplicates.length} duplicate name(s), first module kept:`);
  for (const d of duplicates.slice(0, 20)) console.log(`  ${d}`);
}
